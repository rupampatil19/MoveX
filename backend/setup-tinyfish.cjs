write('backend/routes/dynamicQuests.js', [
"const express = require('express');",
"const router = express.Router();",
"const { startEventResearch } = require('../services/tinyfishService');",
"const DynamicEvent = require('../models/DynamicEvent');",
"",
"function buildWebhookUrl() {",
"  const host = process.env.RENDER_EXTERNAL_HOSTNAME;",
"  if (host) return 'https://' + host + '/api/dynamic-quests/webhook';",
"  const base = process.env.BACKEND_URL || 'http://localhost:5000';",
"  return base.replace(/\\/$/, '') + '/api/dynamic-quests/webhook';",
"}",
"",
"// POST /api/dynamic-quests/generate  { city: 'Pune' }",
"router.post('/generate', async (req, res) => {",
"  const city = req.body && req.body.city;",
"  if (!city) return res.status(400).json({ msg: 'City required' });",
"  try {",
"    const webhookUrl = buildWebhookUrl();",
"    const result = await startEventResearch(city, webhookUrl);",
"    res.json({ status: 'started', city: city, run: result, webhook: webhookUrl });",
"  } catch (err) {",
"    console.error('[dynamic-quests]', err.message);",
"    res.status(500).json({ msg: 'Research failed', error: err.message });",
"  }",
"});",
"",
"// POST /api/dynamic-quests/webhook - TinyFish calls this when research completes",
"router.post('/webhook', async (req, res) => {",
"  try {",
"    const body = req.body || {};",
"    const event = body.event;",
"    if (event && event !== 'run.completed' && event !== 'completed') {",
"      return res.status(200).json({ ignored: true, event: event });",
"    }",
"    const data = body.data || body;",
"    const result = data.result || data;",
"    const events = (result && result.events) ? result.events : (Array.isArray(result) ? result : []);",
"    const city = body.city || data.city || 'Unknown';",
"",
"    let stored = 0;",
"    for (const ev of events) {",
"      const name = (ev && ev.name) ? ev.name : 'Untitled event';",
"      const dateStr = (ev && ev.date) ? ev.date : null;",
"      await DynamicEvent.create({",
"        city: city,",
"        name: name,",
"        date: dateStr,",
"        location: (ev && ev.location) ? ev.location : city,",
"        url: (ev && ev.url) ? ev.url : null,",
"        expiresAt: dateStr ? new Date(dateStr) : new Date(Date.now() + 30 * 24 * 60 * 60 * 1000),",
"      });",
"      stored++;",
"    }",
"    console.log('[dynamic-quests webhook] stored', stored, 'events for', city);",
"    res.json({ ok: true, stored: stored, city: city });",
"  } catch (err) {",
"    console.error('[dynamic-quests webhook]', err.message);",
"    res.status(500).json({ error: err.message });",
"  }",
"});",
"",
"// GET /api/dynamic-quests/events?city=Pune",
"router.get('/events', async (req, res) => {",
"  const city = req.query.city;",
"  const filter = {};",
"  if (city) filter.city = city;",
"  try {",
"    const events = await DynamicEvent.find(filter).sort({ date: 1 }).limit(50);",
"    res.json({ count: events.length, events: events });",
"  } catch (err) {",
"    res.status(500).json({ error: err.message });",
"  }",
"});",
"",
"module.exports = router;",
""].join('\n'));

