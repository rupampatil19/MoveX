export const REGION_LEVEL_THRESHOLDS = [0, 20000, 50000, 100000, 200000];
export const BUILDING_NAMES = ['Tide Hut', 'Wave Dock', 'Aqua Bastion', 'Ocean Citadel', "Poseidon's Hub"];
export const BUILDING_EMOJIS = ['🛖', '⚓', '🏰', '🛯', '🔱'];

export function getRegionLevel(totalEnergy) {
  let level = 1;
  for (let i = 0; i < REGION_LEVEL_THRESHOLDS.length; i++) if (totalEnergy >= REGION_LEVEL_THRESHOLDS[i]) level = i + 1;
  return Math.min(level, 5);
}
export function getBuildingName(totalEnergy) { return BUILDING_NAMES[getRegionLevel(totalEnergy) - 1]; }
export function getBuildingEmoji(totalEnergy) { return BUILDING_EMOJIS[getRegionLevel(totalEnergy) - 1]; }
export function getRegionById(regionId) { return Object.values(CITY_REGIONS).flat().find((r) => r.id === regionId); }

export const CITY_LEVEL_THRESHOLDS = [0, 100000, 250000, 500000, 1000000];
export function getCityLevel(totalEnergy) {
  let level = 1;
  for (let i = 0; i < CITY_LEVEL_THRESHOLDS.length; i++) if (totalEnergy >= CITY_LEVEL_THRESHOLDS[i]) level = i + 1;
  return Math.min(level, 5);
}
export function getCityRequiredEnergy(level) {
  const safe = Math.min(Math.max(level, 1), 5);
  return CITY_LEVEL_THRESHOLDS[safe - 1];
}

